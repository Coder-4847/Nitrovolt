// Dev-only: one car, three-quarter front view, transparent background (landing page art).
// Open /dev/car-solo.html?car=volt
import '@fontsource/barlow-condensed/700.css';
import { AmbientLight, CircleGeometry, DirectionalLight, HemisphereLight, Mesh, MeshBasicMaterial, PMREMGenerator, PerspectiveCamera, Quaternion, Scene, Vector3, WebGLRenderer, CanvasTexture } from 'three';
import { CARS, CarId } from '../src/data/cars';
import { CarView } from '../src/render/CarView';
import { Sky } from '../src/render/env/Sky';
import { THEMES } from '../src/render/env/Theme';

const id = (new URLSearchParams(location.search).get('car') ?? 'volt') as CarId;
const W = 960, H = 540;
const r = new WebGLRenderer({ antialias: true, alpha: true, preserveDrawingBuffer: true });
r.setPixelRatio(1);
r.setSize(W, H);
r.setClearColor(0x000000, 0);
document.body.appendChild(r.domElement);
const scene = new Scene();
const env = new Scene();
const sky = new Sky();
sky.apply(THEMES.forest);
sky.mesh.scale.setScalar(0.05);
env.add(sky.mesh);
scene.environment = new PMREMGenerator(r).fromScene(env, 0.02, 0.1, 200).texture;
scene.add(new HemisphereLight(0xe8f0ff, 0x606878, 1.2), new AmbientLight(0xffffff, 0.15));
const key = new DirectionalLight(0xfff6ea, 2.6);
key.position.set(-5, 8, -4);
scene.add(key);
const rim = new DirectionalLight(0xc8dcff, 1.6);
rim.position.set(6, 3, 6);
scene.add(rim);
await document.fonts.load('700 20px "Barlow Condensed"');
const def = CARS[id];
const p = def.params;
const view = new CarView(id, p, def.livery.primary, def.livery.accent);
view.addDriverLights();
const rest = p.springLenMax * 0.75;
const ground = p.mountY - rest - p.wheelRadius;
view.update({ position: new Vector3(0, -ground, 0), quaternion: new Quaternion().setFromAxisAngle(new Vector3(0, 1, 0), -0.6), springLen: [rest, rest, rest, rest], steer: [-0.3, -0.3, 0, 0], spin: [0, 0, 0, 0] });
view.setSpeed(0);
scene.add(view.root);
// soft contact shadow
const c = document.createElement('canvas');
c.width = c.height = 128;
const g = c.getContext('2d')!;
const grad = g.createRadialGradient(64, 64, 4, 64, 64, 64);
grad.addColorStop(0, 'rgba(0,0,0,0.55)');
grad.addColorStop(1, 'rgba(0,0,0,0)');
g.fillStyle = grad;
g.fillRect(0, 0, 128, 128);
const shadow = new Mesh(new CircleGeometry(1, 32).rotateX(-Math.PI / 2), new MeshBasicMaterial({ map: new CanvasTexture(c), transparent: true, depthWrite: false }));
shadow.scale.set(1.6, 1, 2.9);
shadow.rotation.y = -0.6;
shadow.position.y = 0.01;
scene.add(shadow);
const cam = new PerspectiveCamera(26, W / H, 0.1, 100);
cam.position.set(-4.7, 1.75, -6.2);
cam.lookAt(0, 0.55, 0);
r.render(scene, cam);
document.title = 'ready';
