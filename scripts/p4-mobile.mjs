import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errs=[]; page.on('pageerror', e=>errs.push(e.message));
await page.goto('http://127.0.0.1:5173/');
await page.waitForSelector('#boot', { state: 'detached', timeout: 60000 });
await page.waitForTimeout(800);
await page.screenshot({ path: '/tmp/claude-0/shots/m1_menu.png' });
await page.getByRole('button', { name: 'Campaign' }).tap();
await page.waitForTimeout(1200);
await page.screenshot({ path: '/tmp/claude-0/shots/m2_campaign.png' });
await page.locator('.card:not(.locked):not(.empty)').first().tap();
await page.waitForFunction(() => document.querySelector('.hud'), null, {timeout:15000});
await page.waitForTimeout(3000);
await page.screenshot({ path: '/tmp/claude-0/shots/m3_race.png' });
await page.locator('.tb.men').tap();
await page.waitForTimeout(400);
await page.screenshot({ path: '/tmp/claude-0/shots/m4_pause.png' });
console.log(errs.join('\n') || 'no errors');
await browser.close();
