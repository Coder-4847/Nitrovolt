// Screenshots of the menu flow: landing, main menu, play hub, campaign, training. Usage: node scripts/menu-shots.mjs <outPrefix>
import { chromium } from 'playwright-core';
const prefix = process.argv[2] ?? '/tmp/menu';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: Number(process.env.W ?? 1280), height: Number(process.env.H ?? 720) } });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto('http://127.0.0.1:5173/');
await page.waitForSelector('#boot', { state: 'detached', timeout: 60000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${prefix}_landing.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${prefix}_main.png` });
await page.getByRole('button', { name: /^Play/ }).first().click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${prefix}_play.png` });
await page.locator('.play-tile.big').click();
await page.waitForTimeout(2500);
await page.screenshot({ path: `${prefix}_campaign.png` });
console.log(errs.join('\n') || 'no errors');
await browser.close();
